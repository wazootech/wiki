/**
 * Writes the formatter's WebAssembly plugins into `src/wiki/dprint/plugins.gen.ts`
 * so the engine carries them itself.
 *
 * Run after changing a plugin version in `deno.json` and `package.json`:
 *
 *     bun scripts/embed_dprint.ts
 */
import { readFileSync, writeFileSync } from "node:fs";
import { Buffer } from "node:buffer";
import { brotliCompressSync, constants } from "node:zlib";
import { fromFileUrl } from "@std/path";
import { pluginSources } from "./dprint_sources.ts";

const OUTPUT = fromFileUrl(
  new URL("../src/wiki/dprint/plugins.gen.ts", import.meta.url),
);
/** Wrapped so a version bump diffs as lines rather than one enormous one. */
const COLUMNS = 4000;

function encode(wasm: Uint8Array): string {
  const compressed = brotliCompressSync(wasm, {
    params: { [constants.BROTLI_PARAM_QUALITY]: 11 },
  });
  const text = Buffer.from(compressed).toString("base64");
  const lines: string[] = [];
  for (let at = 0; at < text.length; at += COLUMNS) {
    lines.push(`    "${text.slice(at, at + COLUMNS)}",`);
  }
  return lines.join("\n");
}

const config = JSON.parse(
  readFileSync(new URL("../deno.json", import.meta.url), "utf8"),
) as { imports: Record<string, string> };

const entries = pluginSources().map(({ name, specifier, path }) =>
  `  // ${config.imports[specifier]}\n` +
  `  ${name}: [\n${encode(readFileSync(path))}\n  ].join(""),`
);

writeFileSync(
  OUTPUT,
  `// Generated by scripts/embed_dprint.ts. Do not edit.
//
// Brotli-compressed, base64 WebAssembly formatter plugins from the npm packages
// named below, each published under the MIT license.

export const PLUGINS = {
${entries.join("\n")}
} as const;
`,
);
console.log(`wrote ${entries.length} plugins to ${OUTPUT}`);
